/*
 * 10_developer_ecosystem_graph.sql
 * Dedicated High Tech Product Signal Graph.
 * Keeps inherited influencer tables available while adding a finance-parity
 * domain graph for product portfolios, advocates, partners, buyers, blockers,
 * capacity centers, and signal cases.
