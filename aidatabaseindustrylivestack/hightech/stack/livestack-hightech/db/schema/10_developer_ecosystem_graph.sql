        'change_review_board', 'demand_forecast', 'allocation_plan',
        'capacity_reservation', 'design_ip', 'substrate_material',
        'manufacturing_route', 'quality_gate', 'support_operation',
        'lifecycle_stage'
      )),
      CONSTRAINT tech_graph_risk_ck CHECK (risk_level IN ('low', 'medium', 'high', 'critical'))
    )
  ]';
  DBMS_OUTPUT.PUT_LINE('Created tech_graph_entities.');
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE = -955 THEN
      DBMS_OUTPUT.PUT_LINE('tech_graph_entities already exists.');
