BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE OR REPLACE VIEW developer_ecosystem_edges_v AS
    SELECT
      r.relationship_id,
      r.from_entity,
      r.to_entity,
      src.display_name AS from_name,
      dst.display_name AS to_name,
      r.relationship_type,
      r.strength,
      r.signal_count,
      r.product_value,
      r.evidence_text
    FROM tech_graph_relationships r
    JOIN tech_graph_entities src ON src.entity_id = r.from_entity
    JOIN tech_graph_entities dst ON dst.entity_id = r.to_entity
  ]';
END;
/

BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE PROPERTY GRAPH tech_product_signal_network
      VERTEX TABLES (
        tech_graph_entities KEY (entity_id) LABEL entity
          PROPERTIES (
            entity_id, entity_key, display_name, entity_type,
            influence_score, urgency_score, risk_level, region, city,
            channel, product_value, signal_count, is_priority,
            created_at, updated_at
          ),
        product_signal_cases KEY (case_id) LABEL signal_case
          PROPERTIES (
            case_id, case_ref, case_type, status, urgency_score,
            product_value_at_risk, signal_count, executive_summary,
            created_at, updated_at
          )
      )
      EDGE TABLES (
        tech_graph_relationships KEY (relationship_id)
          SOURCE KEY (from_entity) REFERENCES tech_graph_entities(entity_id)
          DESTINATION KEY (to_entity) REFERENCES tech_graph_entities(entity_id)
          LABEL related_to
          PROPERTIES (
            relationship_id, from_entity, to_entity, relationship_type,
            strength, signal_count, product_value, evidence_text, created_at
          ),
        product_signal_case_entities KEY (case_entity_id)
          SOURCE KEY (case_id) REFERENCES product_signal_cases(case_id)
          DESTINATION KEY (entity_id) REFERENCES tech_graph_entities(entity_id)
          LABEL contains_entity
          PROPERTIES (
            case_entity_id, case_id, entity_id, role,
            evidence_score, evidence_note
          )
      )
      OPTIONS (ENFORCED MODE)
  ]';
  DBMS_OUTPUT.PUT_LINE('Created property graph tech_product_signal_network.');
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE = -955 THEN
      DBMS_OUTPUT.PUT_LINE('tech_product_signal_network already exists.');
    ELSE
      RAISE;
    END IF;
END;
/

ALTER PROPERTY GRAPH tech_product_signal_network COMPILE;

COMMENT ON TABLE tech_graph_entities IS 'High Tech Product Signal Graph vertices: product advocates, partners, portfolios, customer commitments, design architectures, product lifecycle blockers, capacity centers, and signal clusters.';
COMMENT ON TABLE tech_graph_relationships IS 'High Tech Product Signal Graph edges connecting product signals, products, customer commitments, blockers, architectures, fabs, contract manufacturing, and capacity centers.';
COMMENT ON TABLE product_signal_cases IS 'High-tech signal cases that group urgent customer demand, supplier risk, BOM/ECO exposure, field quality, warranty analytics, blockers, and product value at risk.';
COMMENT ON TABLE product_signal_case_entities IS 'Membership table linking product signal cases to graph entities with a role and evidence score.';
