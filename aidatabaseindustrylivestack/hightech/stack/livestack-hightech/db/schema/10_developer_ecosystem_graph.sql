      signal_count NUMBER(8) DEFAULT 0 NOT NULL,
      is_priority NUMBER(1) DEFAULT 0 NOT NULL,
      created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT tech_graph_entity_type_ck CHECK (entity_type IN (
        'advocate', 'partner', 'portfolio', 'buyer', 'architecture',
        'blocker', 'capacity_center', 'signal_cluster', 'fab',
        'wafer_lot', 'process_step', 'yield_metric', 'bom_component',
